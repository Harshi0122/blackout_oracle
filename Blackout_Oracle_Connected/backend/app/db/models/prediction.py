"""
Blackout Oracle - Prediction Database Model.

Stores predictions generated by the Blackout Oracle prediction and
risk-analysis systems.

Predictions may concern:

- Asset failures
- Substation failures
- Feeder failures
- Generator outages
- Overloads
- Voltage anomalies
- Frequency anomalies
- Blackout probability
- Cascading-failure probability
- Weather-related grid failures
- Regional power disruptions

A prediction represents what the system EXPECTS may happen.

It is intentionally separate from Incident and Outage records, which
represent events that have actually been detected or confirmed.

IMPORTANT
---------

Predictions are advisory analytical outputs.

They do NOT directly control electrical-grid infrastructure.
"""


from __future__ import annotations

from datetime import datetime, timezone
from uuid import uuid4

from sqlalchemy import (
    Boolean,
    DateTime,
    Float,
    Index,
    Integer,
    String,
    Text,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


# ============================================================
# ENUMS
# ============================================================


class PredictionType:
    """
    Type of prediction generated by Blackout Oracle.
    """

    ASSET_FAILURE = "asset_failure"
    SUBSTATION_FAILURE = "substation_failure"
    TRANSFORMER_FAILURE = "transformer_failure"
    FEEDER_FAILURE = "feeder_failure"
    TRANSMISSION_FAILURE = "transmission_failure"
    GENERATOR_OUTAGE = "generator_outage"

    OVERLOAD = "overload"
    VOLTAGE_ANOMALY = "voltage_anomaly"
    FREQUENCY_ANOMALY = "frequency_anomaly"

    DEMAND_SURGE = "demand_surge"
    GENERATION_SHORTAGE = "generation_shortage"

    BLACKOUT = "blackout"
    CASCADING_FAILURE = "cascading_failure"

    WEATHER_IMPACT = "weather_impact"
    FLOOD_IMPACT = "flood_impact"
    STORM_IMPACT = "storm_impact"
    EXTREME_HEAT = "extreme_heat"

    UNKNOWN = "unknown"


class PredictionStatus:
    """
    Lifecycle state of a prediction.
    """

    ACTIVE = "active"
    CONFIRMED = "confirmed"
    EXPIRED = "expired"
    CANCELLED = "cancelled"
    INVALIDATED = "invalidated"


class PredictionSeverity:
    """
    Expected severity of the predicted event.
    """

    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class PredictionOutcome:
    """
    Outcome used for evaluating prediction accuracy.
    """

    PENDING = "pending"
    TRUE_POSITIVE = "true_positive"
    FALSE_POSITIVE = "false_positive"
    TRUE_NEGATIVE = "true_negative"
    FALSE_NEGATIVE = "false_negative"
    UNKNOWN = "unknown"


# ============================================================
# PREDICTION MODEL
# ============================================================


class Prediction(Base):
    """
    SQLAlchemy model representing a Blackout Oracle prediction.
    """

    __tablename__ = "predictions"

    # ========================================================
    # PRIMARY KEY
    # ========================================================

    id: Mapped[str] = mapped_column(
        String(50),
        primary_key=True,
        default=lambda: (
            f"PRD-{uuid4().hex[:12].upper()}"
        ),
    )

    # ========================================================
    # PREDICTION CLASSIFICATION
    # ========================================================

    prediction_type: Mapped[str] = mapped_column(
        String(60),
        nullable=False,
        index=True,
    )

    status: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
        default=PredictionStatus.ACTIVE,
        index=True,
    )

    severity: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default=PredictionSeverity.MEDIUM,
        index=True,
    )

    title: Mapped[str] = mapped_column(
        String(300),
        nullable=False,
    )

    description: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    # ========================================================
    # LOCATION
    # ========================================================

    region_id: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        index=True,
    )

    region_name: Mapped[str | None] = mapped_column(
        String(200),
        nullable=True,
    )

    latitude: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    longitude: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    # ========================================================
    # TARGET GRID INFRASTRUCTURE
    # ========================================================

    asset_id: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        index=True,
    )

    substation_id: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        index=True,
    )

    feeder_id: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        index=True,
    )

    bus_id: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        index=True,
    )

    generator_id: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        index=True,
    )

    # ========================================================
    # PREDICTION PROBABILITIES
    # ========================================================

    probability: Mapped[float] = mapped_column(
        Float,
        nullable=False,
        default=0.0,
        index=True,
    )

    blackout_probability: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    cascade_probability: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    failure_probability: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    confidence: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    # ========================================================
    # PREDICTED IMPACT
    # ========================================================

    predicted_load_loss_mw: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    predicted_generation_loss_mw: Mapped[
        float | None
    ] = mapped_column(
        Float,
        nullable=True,
    )

    predicted_affected_customers: Mapped[
        int | None
    ] = mapped_column(
        Integer,
        nullable=True,
    )

    predicted_affected_assets: Mapped[
        int | None
    ] = mapped_column(
        Integer,
        nullable=True,
    )

    predicted_affected_regions: Mapped[
        int | None
    ] = mapped_column(
        Integer,
        nullable=True,
    )

    # ========================================================
    # PREDICTED ELECTRICAL CONDITIONS
    # ========================================================

    predicted_voltage_kv: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    predicted_frequency_hz: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    predicted_loading_percent: Mapped[
        float | None
    ] = mapped_column(
        Float,
        nullable=True,
    )

    predicted_demand_mw: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    predicted_generation_mw: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    # ========================================================
    # TIME HORIZON
    # ========================================================

    prediction_horizon_minutes: Mapped[
        int | None
    ] = mapped_column(
        Integer,
        nullable=True,
    )

    predicted_event_time: Mapped[
        datetime | None
    ] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        index=True,
    )

    prediction_expiry_time: Mapped[
        datetime | None
    ] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        index=True,
    )

    # ========================================================
    # WEATHER CONTRIBUTION
    # ========================================================

    weather_related: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
        index=True,
    )

    weather_risk_score: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    flood_risk_score: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    storm_risk_score: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    temperature_risk_score: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    # ========================================================
    # MODEL INFORMATION
    # ========================================================

    model_name: Mapped[str | None] = mapped_column(
        String(200),
        nullable=True,
    )

    model_version: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
    )

    model_type: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
    )

    # ========================================================
    # FEATURE / EXPLANATION INFORMATION
    # ========================================================

    top_features_json: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    explanation: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    reasoning_summary: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    # ========================================================
    # AI AGENT INFORMATION
    # ========================================================

    ai_analyzed: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
        index=True,
    )

    ai_summary: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    ai_model_name: Mapped[str | None] = mapped_column(
        String(200),
        nullable=True,
    )

    ai_model_version: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
    )

    # ========================================================
    # SIMULATION
    # ========================================================

    simulation_required: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
    )

    simulation_completed: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
    )

    simulation_id: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        index=True,
    )

    simulation_result: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    # ========================================================
    # RECOMMENDATION
    # ========================================================

    recommendation_generated: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
    )

    recommendation_id: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        index=True,
    )

    # ========================================================
    # ACTUAL OUTCOME
    # ========================================================

    outcome: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
        default=PredictionOutcome.PENDING,
        index=True,
    )

    actual_event_occurred: Mapped[bool | None] = mapped_column(
        Boolean,
        nullable=True,
    )

    actual_incident_id: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        index=True,
    )

    actual_outage_id: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        index=True,
    )

    actual_event_time: Mapped[
        datetime | None
    ] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    # ========================================================
    # ACCURACY METRICS
    # ========================================================

    prediction_error: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    absolute_error: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    # ========================================================
    # SOURCE / CORRELATION
    # ========================================================

    source: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
    )

    request_id: Mapped[str | None] = mapped_column(
        String(150),
        nullable=True,
        index=True,
    )

    correlation_id: Mapped[str | None] = mapped_column(
        String(150),
        nullable=True,
        index=True,
    )

    # ========================================================
    # ADDITIONAL DATA
    # ========================================================

    metadata_json: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    # ========================================================
    # TIMESTAMPS
    # ========================================================

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(
            timezone.utc
        ),
        index=True,
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(
            timezone.utc
        ),
        onupdate=lambda: datetime.now(
            timezone.utc
        ),
    )

    # ========================================================
    # DATABASE INDEXES
    # ========================================================

    __table_args__ = (
        Index(
            "ix_predictions_region_type",
            "region_id",
            "prediction_type",
        ),
        Index(
            "ix_predictions_region_created",
            "region_id",
            "created_at",
        ),
        Index(
            "ix_predictions_asset_created",
            "asset_id",
            "created_at",
        ),
        Index(
            "ix_predictions_status_probability",
            "status",
            "probability",
        ),
        Index(
            "ix_predictions_event_time",
            "predicted_event_time",
            "prediction_expiry_time",
        ),
        Index(
            "ix_predictions_outcome",
            "outcome",
            "actual_event_occurred",
        ),
        Index(
            "ix_predictions_blackout_cascade",
            "blackout_probability",
            "cascade_probability",
        ),
    )

    # ========================================================
    # REPRESENTATION
    # ========================================================

    def __repr__(self) -> str:
        return (
            "<Prediction("
            f"id='{self.id}', "
            f"type='{self.prediction_type}', "
            f"probability={self.probability}, "
            f"status='{self.status}', "
            f"outcome='{self.outcome}'"
            ")>"
        )


